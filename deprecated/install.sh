#!/bin/bash
# Install Wow Forever helpers onto a DroidDeck guest. Run as root on the deck.
# Does not install WoW, Battle.net, Proton, or a GPU driver.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
DEST_BIN="${DEST_BIN:-/usr/local/bin}"
DEST_LIB="${DEST_LIB:-/usr/local/lib}"
DEST_ENV="${DEST_ENV:-/usr/local/etc/wow-forever.env}"
STEAM_ROOT="${STEAM_COMPAT_CLIENT_INSTALL_PATH:-/root/.local/share/Steam}"

install -d "$DEST_BIN" "$DEST_LIB" "$(dirname "$DEST_ENV")"
install -m 0755 "$ROOT/scripts/Launch.sh" "$DEST_BIN/Launch.sh"
install -m 0755 "$ROOT/scripts/Launch-WoW.sh" "$DEST_BIN/Launch-WoW.sh"
install -m 0755 "$ROOT/scripts/Launch-WoW-DroidDeckProton.sh" "$DEST_BIN/Launch-WoW-DroidDeckProton.sh"
install -m 0755 "$ROOT/scripts/Launch-BattleNet.sh" "$DEST_BIN/Launch-BattleNet.sh"
install -m 0755 "$ROOT/scripts/Launch-BattleNet-DroidDeckProton.sh" "$DEST_BIN/Launch-BattleNet-DroidDeckProton.sh"
install -m 0755 "$ROOT/scripts/droiddeck-steamgame-stamp.sh" "$DEST_BIN/droiddeck-steamgame-stamp.sh"
install -m 0755 "$ROOT/scripts/droiddeck-steam-stamper-wrap.sh" "$DEST_BIN/droiddeck-steam-stamper-wrap.sh"
if [[ -f "$ROOT/scripts/Launch-WoW-Storage.sh" ]]; then
  install -m 0755 "$ROOT/scripts/Launch-WoW-Storage.sh" "$DEST_BIN/Launch-WoW-Storage.sh"
fi
install -m 0755 "$ROOT/scripts/patch-ntdll-teb-table-stub.py" "$DEST_BIN/patch-ntdll-teb-table-stub.py"
if [[ -f "$ROOT/scripts/patch-ntdll-nls-fallback.py" ]]; then
  install -m 0755 "$ROOT/scripts/patch-ntdll-nls-fallback.py" "$DEST_BIN/patch-ntdll-nls-fallback.py"
fi
install -m 0755 "$ROOT/shim/libsigctx_zero.so" "$DEST_LIB/libsigctx_zero.so"

offsets="${WOW_TEBSTUB_OFFSETS:-b0a68:43240}"
patched=0
shopt -s nullglob
for dll in "$STEAM_ROOT/compatibilitytools.d"/DroidDeck-Proton*/files/lib/wine/aarch64-windows/ntdll.dll; do
  python3 "$DEST_BIN/patch-ntdll-teb-table-stub.py" "$dll"
  patched=1
  so="${dll%/aarch64-windows/ntdll.dll}/aarch64-unix/ntdll.so"
  if [[ -f "$so" && -x "$DEST_BIN/patch-ntdll-nls-fallback.py" ]]; then
    if python3 "$DEST_BIN/patch-ntdll-nls-fallback.py" "$so"; then
      echo "NLS fallback patched $so"
    else
      echo "install: NLS fallback skipped for $so (layout mismatch is OK on a newer Proton)" >&2
    fi
  fi
  if [[ -f "$so" ]] && command -v nm >/dev/null 2>&1; then
    table="$(nm "$so" 2>/dev/null | awk '/KeServiceDescriptorTable/{print $1; exit}')"
    disp="$(nm "$so" 2>/dev/null | awk '/__wine_syscall_dispatcher$/{print $1; exit}')"
    if [[ -n "$table" && -n "$disp" ]]; then
      offsets="${table}:${disp}"
      echo "ntdll.so offsets $offsets from $so"
    fi
  fi
done
shopt -u nullglob

if [[ "$patched" -eq 0 ]]; then
  echo "install: no DroidDeck-Proton ntdll.dll found under $STEAM_ROOT/compatibilitytools.d" >&2
  echo "install: scripts are in place; patch ntdll after Proton is installed" >&2
fi

{
  echo "# Generated by wow-forever-droiddeck install.sh"
  echo "WOW_SIGSHIM=$DEST_LIB/libsigctx_zero.so"
  echo "WOW_TEBSTUB_OFFSETS=$offsets"
  echo "# After the Battle.net Steam shortcut exists, set its compatdata name:"
  echo "# BNET_APPID=4153382437"
} >"$DEST_ENV"
chmod 0644 "$DEST_ENV"

echo "installed launchers to $DEST_BIN"
echo "installed shim to $DEST_LIB/libsigctx_zero.so"
echo "wrote $DEST_ENV"
echo
echo "Steam next:"
echo "  1. Battle.net shortcut, DroidDeck-Proton, launch options: $DEST_BIN/Launch-BattleNet.sh %command%"
echo "  2. Install WoW Forever to C:\\Program Files (x86)\\World of Warcraft"
echo "  3. Play shortcut target: $DEST_BIN/Launch-WoW.sh"
echo "  4. If play misses the install, put BNET_APPID=<Battle.net compatdata id> in $DEST_ENV"
